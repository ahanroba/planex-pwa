/**
 * Renders an avatar for a mentor with oceanic glass border and smart automatic fallback on image load error
 * @param {Object} mentor - Mentor data object
 * @param {number} size - Avatar diameter in pixels (default 56)
 * @returns {string} HTML string
 */
export function renderMentorAvatar(mentor, size = 56) {
  const photo = mentor.photoUrl || mentor.avatarUrl || mentor.image;
  const avatarBg = mentor.avatarBg || 'rgba(56, 189, 248, 0.15)';
  const avatarBorder = mentor.avatarBorder || 'rgba(56, 189, 248, 0.4)';
  const icon = mentor.avatar || '👩‍⚕️';
  const fontSize = Math.round(size * 0.46);

  if (photo) {
    return `
      <div style="width: ${size}px; height: ${size}px; border-radius: 50%; padding: 2.5px; background: linear-gradient(135deg, rgba(255, 255, 255, 0.5), rgba(45, 212, 191, 0.8)); box-shadow: 0 0 18px rgba(45, 212, 191, 0.5), 0 4px 14px rgba(0,0,0,0.35); flex-shrink: 0; display: flex; align-items: center; justify-content: center; backdrop-filter: blur(8px);">
        <img src="${photo}" alt="${mentor.name}" loading="lazy" style="width: 100%; height: 100%; border-radius: 50%; object-fit: cover; display: block; border: 1.5px solid rgba(255, 255, 255, 0.9);" onerror="this.onerror=null; this.parentElement.style.padding='0'; this.parentElement.style.background='transparent'; this.parentElement.innerHTML='<div style=\\'width:100%;height:100%;border-radius:50%;background:${avatarBg};border:1.5px solid ${avatarBorder};display:flex;align-items:center;justify-content:center;font-size:${fontSize}px;box-shadow:0 4px 14px rgba(0,0,0,0.3);backdrop-filter:blur(8px);\\'>${icon}</div>';" />
      </div>
    `;
  }

  return `
    <div style="width: ${size}px; height: ${size}px; border-radius: 50%; background: ${avatarBg}; border: 1.5px solid ${avatarBorder}; display: flex; align-items: center; justify-content: center; font-size: ${fontSize}px; flex-shrink: 0; box-shadow: 0 4px 14px rgba(0,0,0,0.3); backdrop-filter: blur(8px);">
      ${icon}
    </div>
  `;
}

